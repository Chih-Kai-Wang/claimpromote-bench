def verify_submission_surface() -> None:
    forbidden_paths = [
        "external-audit/v1/submissions/reviewer-01-submission.json",
        "external-audit/v1/submissions/reviwer-02-submission.json",
        "docs/HUMAN_AUDIT_ETHICS_CHECKLIST.md",
    ]
    for path in forbidden_paths:
        if (ROOT / path).exists():
            raise RuntimeError(f"human-study path remains: {path}")

    forbidden_phrases = (
        "Supplementary human audit",
        "Human policy audit",
        "Reviewer 1 &",
        "Reviewer 2 &",
        "mixed / not PASS",
        "human audit ethics",
    )
    submission_files = (
        "technical-report/main.tex",
        "README.md",
        "technical-report/SUBMISSION_GATE.md",
        "technical-report/SUBMISSION_GATE_V2.md",
        "docs/ANONYMOUS_REVIEW_BUNDLE.md",
        "docs/EXPERIMENTS.md",
        "docs/ICLR_2027_V2_REVIEW_RISK_AUDIT.md",
        "docs/SUBMISSION_METADATA_DRAFT.md",
    )
    for path in submission_files:
        text = read(path)
        for phrase in forbidden_phrases:
            if phrase.lower() in text.lower():
                raise RuntimeError(f"human-audit phrase remains in {path}: {phrase}")


def main() -> int:
    migrate_manuscript()
    migrate_readme()
    migrate_experiments()
    migrate_anonymous_bundle_doc()
    migrate_submission_metadata()
    migrate_risk_audit()
    migrate_submission_gates()
    delete_human_study_material()
    verify_submission_surface()
    print("human-audit-removal: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
