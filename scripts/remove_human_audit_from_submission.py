#!/usr/bin/env python3
"""Remove the supplementary human audit from the submission-facing project state.

The benchmark keeps synthetic review-status semantics because they are part of the policy task.
This migration removes the actual two-person annotation study, its records, its ethics gate, and all
paper-facing claims based on it. Credibility is instead grounded in machine-checkable construction,
precommitment, executable artifacts, controlled comparisons, and artifact-only recomputation.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def write(path: str, content: str) -> None:
    (ROOT / path).write_text(content, encoding="utf-8", newline="\n")


def sub_once(text: str, pattern: str, replacement: str, *, label: str) -> str:
    updated, count = re.subn(pattern, lambda _match: replacement, text, count=1, flags=re.DOTALL)
    if count != 1:
        raise RuntimeError(f"expected one {label} replacement, found {count}")
    return updated


def remove_if_present(path: str) -> None:
    target = ROOT / path
    if target.exists():
        target.unlink()


def remove_empty_parents(path: str, stop: str) -> None:
    current = (ROOT / path).parent
    stop_path = ROOT / stop
    while current != stop_path and current.exists():
        try:
            current.rmdir()
        except OSError:
            break
        current = current.parent


def migrate_manuscript() -> None:
    path = "technical-report/main.tex"
    text = read(path)
    text = sub_once(
        text,
        r"\n\\subsection\{Supplementary human audit\}.*?(?=\n\\section\{Discussion\})",
        "\n",
        label="human-audit manuscript section",
    )
    text = sub_once(
        text,
        r"\\paragraph\{Benchmark construction and human audit\.\}.*?(?=\n\\section\{Reproducibility and Artifact Policy\})",
        """\\paragraph{Benchmark construction and label scope.}
The author designed the policy, controlled factors, and item generator. The gold action is therefore a deterministic policy output rather than a survey of human preference. To make this construction auditable, a separate public pair-contract check verifies all 20 factors, confirms that each valid member is \\allow{} and each invalid member is non-\\allow{}, recomputes every gold decision from the versioned policy, and rejects any pair whose members differ outside the registered JSON pointers. Deterministic rebuilding, executable checks, the hidden commitment, shortcut checks, and meaning-preserving transformations further restrict post-hoc flexibility. These checks strengthen implementation and construction validity, but they do not establish that the author-defined policy is a universal scientific norm. A passing Lean artifact still proves only the exact encoded statement in the pinned environment.
""",
        label="benchmark-construction limitation",
    )
    marker = "\n\\section{Intervention Arms}\n"
    if "\\subsection{Machine-checkable validation strategy}" not in text:
        if marker not in text:
            raise RuntimeError("cannot locate Intervention Arms insertion point")
        validation = r"""
\subsection{Machine-checkable validation strategy}

The benchmark does not use human annotations as a source of gold labels. Instead, its credibility rests on a chain of checks whose scope is explicit. The public pair-contract audit verifies that each pair changes only its registered policy field, that the valid and invalid sides have the required actions, and that all 40 public labels are exactly reproduced by the versioned oracle. Dataset generation is deterministic; numerical artifacts are recomputed with exact rational arithmetic; formal artifacts are replayed with the pinned Lean kernel; shortcut and metamorphic checks test identifier, ordering, and irrelevant-evidence invariance; and hidden data and exact prompts were committed before scored inference. Finally, both the hidden study and the public formatting control are recomputed from immutable source artifacts without new model calls. None of these checks turns the policy into human consensus, but together they make the reported benchmark behavior independently inspectable and difficult to change after results are known.
"""
        text = text.replace(marker, f"\n{validation}{marker}", 1)
    text = text.replace(
        "AI systems are not listed as authors and were not used as independent human reviewers.",
        "AI systems are not listed as authors.",
    )
    write(path, text)


